"""Central metric registry and transparent metric definitions for Token Ledger.

Implements WP08 and Rebuild Plan Row 53 (Transparent Metric Definitions):
- Versioned central metric registry with explicit formulas and denominators.
- Categorization of reported, calculated, inferred, financial, and timing metrics.
- Explicit counter semantics (disjoint billable tokens vs non-additive reasoning subset).
- Speed basis (eligible timed requests with generation duration, excluding untimed requests).
- Financial basis (effective dated rate cards, historical FX, and actual billed amounts).
"""

from __future__ import annotations

from dataclasses import asdict, dataclass
from typing import Any, Dict, List, Optional, Tuple


@dataclass(frozen=True)
class MetricDefinition:
    """Metadata definition explaining how a metric is calculated, its units, denominator, and provenance."""

    metric_id: str
    name: str
    family: str
    category: str  # 'reported' | 'calculated' | 'inferred' | 'financial' | 'timing'
    version: str
    units: str  # 'tokens', 'USD', 'INR', 'ms', 'tps', 'percentage', 'count', 'ratio'
    formula: str
    denominator: Optional[str]
    counter_semantics: str  # 'disjoint_billable' | 'subset' | 'aggregate' | 'count'
    cost_basis: Optional[str]
    timing_basis: Optional[str]
    description: str
    provenance: str

    def to_dict(self) -> Dict[str, Any]:
        return asdict(self)


